-- 订单管理数据库初始化脚本
-- MySQL 容器首次启动时会自动执行 /docker-entrypoint-initdb.d/ 下的 .sql 文件

-- 关键：把当前连接的字符集设为 utf8mb4，否则 docker-entrypoint 的 mysql 客户端
-- 默认以 latin1 读取本文件，中文数据会被二次编码成乱码（mojibake）。
SET NAMES utf8mb4;

CREATE DATABASE IF NOT EXISTS order_db DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE order_db;

-- 订单表
CREATE TABLE IF NOT EXISTS t_order (
    id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    order_no      VARCHAR(64)     NOT NULL COMMENT '订单号',
    customer_name VARCHAR(64)     NOT NULL COMMENT '客户名称',
    phone         VARCHAR(20)     NOT NULL COMMENT '客户手机号',
    status        TINYINT         NOT NULL DEFAULT 1 COMMENT '订单状态：1-未支付 2-已支付 3-已取消',
    amount        DECIMAL(12,2)   NOT NULL DEFAULT 0.00 COMMENT '订单金额',
    created_at    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    remark        VARCHAR(255)    DEFAULT NULL COMMENT '备注',
    PRIMARY KEY (id),
    UNIQUE KEY uk_order_no (order_no),
    KEY idx_status (status),
    KEY idx_created_at (created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '订单表';

